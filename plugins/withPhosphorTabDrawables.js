const fs = require('fs')
const path = require('path')
const { withDangerousMod } = require('expo/config-plugins')
const tabIcons = require('../src/shared/config/tabIcons.json')

// Writes the native tab bar's Phosphor icons into the Android app as vector
// drawables, so native tabs load them by name
// (`<NativeTabs.Trigger.Icon drawable=… />`). A drawable is the fastest
// icon source native tabs accept on Android: it loads from app resources
// with no image decode and no JS rendering, and is sharp at every density.
//
// The paths come from @phosphor-icons/core, the official Phosphor SVGs that
// phosphor-react-native is built from: regular weight for an idle tab, fill
// weight for the selected tab. android/ is generated; never edit the output.

const VIEWBOX = '0 0 256 256'
const SIZE_DP = 24

function svgPaths(name, weight) {
  const file = weight === 'fill' ? `${name}-fill.svg` : `${name}.svg`
  const svg = fs.readFileSync(
    require.resolve(`@phosphor-icons/core/assets/${weight}/${file}`),
    'utf8',
  )
  // A vector drawable has no <circle>, <rect> or transforms. Fail the
  // prebuild rather than drop part of an icon.
  const tags = [...svg.matchAll(/<([a-zA-Z]+)/g)].map((m) => m[1])
  if (tags.some((tag) => tag !== 'svg' && tag !== 'path')) {
    throw new Error(`[withPhosphorTabDrawables] ${file}: not paths only`)
  }
  if (!svg.includes(`viewBox="${VIEWBOX}"`)) {
    throw new Error(`[withPhosphorTabDrawables] ${file}: unexpected viewBox`)
  }
  return [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
}

function vectorDrawable(paths) {
  // The colour is a placeholder: the tab bar tints every icon itself.
  const body = paths
    .map(
      (d) => `  <path android:fillColor="#FF000000" android:pathData="${d}" />`,
    )
    .join('\n')
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withPhosphorTabDrawables.js. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
  android:width="${SIZE_DP}dp"
  android:height="${SIZE_DP}dp"
  android:viewportWidth="256"
  android:viewportHeight="256">
${body}
</vector>
`
}

module.exports = (config) =>
  withDangerousMod(config, [
    'android',
    (config) => {
      const dir = path.join(
        config.modRequest.platformProjectRoot,
        'app/src/main/res/drawable',
      )
      fs.mkdirSync(dir, { recursive: true })
      for (const { phosphor, drawable } of Object.values(tabIcons)) {
        const files = [
          [drawable.default, 'regular'],
          [drawable.selected, 'fill'],
        ]
        for (const [name, weight] of files) {
          fs.writeFileSync(
            path.join(dir, `${name}.xml`),
            vectorDrawable(svgPaths(phosphor, weight)),
          )
        }
      }
      return config
    },
  ])
